# 商品名にこれらの接尾語が続く場合、直前の言葉（PRODUCT_TYPE_TEMPLATESの
# キーワード）は商品本体ではなく、付属品・対応機能・仕様として書かれている
# とみなす（例：「リモコン付き加湿器」の「リモコン」は商品本体ではなく、
# 加湿器の付属品としての言及）。商品タイトル内の「本体名＋特徴＋付属品＋
# 用途＋広告ワード」が混在していても、商品本体の判定を特徴語・付属品が
# 上書きしないようにするための汎用的な仕組み（description-genre-002対応。
# 個別の商品名をハードコードするのではなく、キーワードの前後関係で判定する）。
_FEATURE_MENTION_SUFFIX_PATTERN = re.compile(r"^(付き|対応|式|機能|内蔵)")

# 商品名にこれらの語が直前にある場合、直後の言葉（PRODUCT_TYPE_TEMPLATES
# のキーワード）は商品本体ではなく、レビュー投稿・購入特典・おまけとして
# 別途もらえる物の言及とみなす（例：「レビューでスポンジ【マーナ公式】
# キッチンツール5点セット」の「スポンジ」は、キッチンツール本体とは別に
# レビュー投稿でもらえる特典であり、商品本体ではない）。商品タイトル内の
# 「販促文＋本体名＋特徴」が混在していても、商品本体の判定を販促の特典
# 語が上書きしないようにするための汎用的な仕組み（description-
# genre-010対応。_FEATURE_MENTION_SUFFIX_PATTERN（付属品の接尾語除外）と
# 対になる、特典の接頭語除外）。
_PROMOTIONAL_MENTION_PREFIX_PATTERN = re.compile(
    r"(レビューで|レビュー特典|レビュー投稿で|購入特典|プレゼント|おまけ)$"
)

# 「◯◯ではない」「◯◯では味わえない」「◯◯不使用」のような否定文脈に
# ある語は、商品本体ではなく「そうではないもの」の言及であるため、商品
# 本体判定から除外する（例：「レトルトでは味わえない本格カレー」の
# 「レトルト」は、レトルト商品ではないと否定する文脈にあり、商品本体
# ではない。「アルコール不使用 除菌シート」の「アルコール」も同様）。
# _PROMOTIONAL_MENTION_PREFIX_PATTERN（特典の接頭語除外）・
# _FEATURE_MENTION_SUFFIX_PATTERN（付属品の接尾語除外）と同じ考え方の、
# 否定文脈の除外（description-genre-012対応）。
_NEGATION_MENTION_SUFFIX_PATTERN = re.compile(r"^(?:ではない|では.{0,10}?ない|不使用)")
_NEGATION_MENTION_PREFIX_PATTERN = re.compile(r"非$")

# 「オムツ」「うどん」「スポンジ」「ハンガー」「水垢」は、より具体的な
# 商品名（マミーポコパンツ・ひもかわうどん・ほこり取りスポンジ・
# ハンガーラック・マルチクロス等）に一致しなかった場合の“商品ジャンルと
# しての最後の保険”として登録した、意図的に汎用的なキーワード。そのため、
# 同じ商品名に他の（より具体的な）商品タイプキーワードが一致する場合は、
# 登場位置に関わらずそちらを優先する（description-genre-006/008/010
# 対応。「おむつペール」「おむつストッカー」のように、商品本体は紙おむつ
# ではないのに「オムツ」という語だけを含む商品名で誤って紙おむつ用
# テンプレートが選ばれる問題への対応。「ハンガー」も同様に、「ハンガー
# ラック」（業務用の衣類収納什器）という別商品の一部分（プレフィックス）
# として登場することがあり、「ハンガー」単体の商品と誤認されていた。
# 「水垢」も、「マルチクロス」等の商品名に用途の1つとして「水垢取り」が
# 含まれる場合に、商品本体（水垢取り専用シート）と誤認されていた。
# 商品名の中でこれらの汎用語がたまたま先に登場していても、他の具体的な
# 商品タイプ語があればそちらを優先するための汎用的な優先度）。
_GENERIC_FALLBACK_PRODUCT_TYPE_KEYWORDS: frozenset[str] = frozenset(
    {"オムツ", "うどん", "スポンジ", "ハンガー", "水垢"}
)


def _iter_product_type_keyword_matches(name: str):
    """商品名の中からPRODUCT_TYPE_TEMPLATESのキーワードに一致する
    (キーワード, テンプレート)を、優先度の高い順に返すジェネレーター。

    同じキーワードが複数回登場する場合、「◯◯付き」等の付属品・対応機能
    としての言及（_FEATURE_MENTION_SUFFIX_PATTERN）や、「レビューで◯◯」
    等のレビュー特典・購入特典としての言及（_PROMOTIONAL_MENTION_
    PREFIX_PATTERN）はスキップし、商品本体としての言及だけを対象にする。
    どの登場箇所も商品本体としての言及ではなかった場合、そのキーワードは
    一致なしとして次のキーワードに進む。

    複数の異なる商品タイプキーワードが同じ商品名に登場する場合（例：
    「サーキュレーター」と「扇風機」が両方とも商品名に含まれる商品）、
    PRODUCT_TYPE_TEMPLATESの登録順ではなく、商品名の中で先に登場する
    キーワードを優先する（商品タイトルは通常、最初に主要な商品名を
    書くため。description-genre-004対応：SEO目的で複数の商品タイプ語が
    混在する商品名でも、実際の商品本体を優先しやすくするための汎用的な
    仕組み）。

    ただし、_GENERIC_FALLBACK_PRODUCT_TYPE_KEYWORDS（オムツ・うどん等、
    意図的に汎用的な最後の保険として登録したキーワード）は、登場位置に
    関わらず他の具体的な商品タイプキーワードより優先度を下げる
    （「具体的な複合商品名 > 商品本体を表す名詞」を、商品名内の位置だけ
    でなくキーワードの具体性でも判定するための仕組み。
    description-genre-006対応）。
    """
    candidates: list[tuple[int, int, int, str, _PostTemplate]] = []
    for order, (keyword, template) in enumerate(PRODUCT_TYPE_TEMPLATES):
        is_generic_fallback = keyword in _GENERIC_FALLBACK_PRODUCT_TYPE_KEYWORDS
        for match in re.finditer(re.escape(keyword), name):
            remainder = name[match.end():]
            if _FEATURE_MENTION_SUFFIX_PATTERN.match(remainder):
                continue
            if _NEGATION_MENTION_SUFFIX_PATTERN.match(remainder):
                continue
            prefix = name[: match.start()]
            if _PROMOTIONAL_MENTION_PREFIX_PATTERN.search(prefix):
                continue
            if _NEGATION_MENTION_PREFIX_PATTERN.search(prefix):
                continue
            candidates.append((int(is_generic_fallback), match.start(), order, keyword, template))
            break
    candidates.sort(key=lambda item: (item[0], item[1], item[2]))
    for _tier, _start, _order, keyword, template in candidates:
        yield keyword, template


def _match_product_type(name: str) -> _PostTemplate | None:
    """商品名から、具体的な商品の種類が分かるテンプレートを返す。無ければNone。

    「ドライヤースタンド」のように、同じキーワードでも周辺語（文脈）に
    よって用途が異なる場合は、_PRODUCT_TYPE_CONTEXT_OVERRIDESを先に確認する。
    """
    for keyword, context_words, template in _PRODUCT_TYPE_CONTEXT_OVERRIDES:
        if keyword in name and any(word in name for word in context_words):
            return template
    for _keyword, template in _iter_product_type_keyword_matches(name):
        return template
    return None


